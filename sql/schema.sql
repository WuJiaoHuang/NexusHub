CREATE DATABASE IF NOT EXISTS cityeats DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE cityeats;

DROP TABLE IF EXISTS tb_voucher_order;
DROP TABLE IF EXISTS tb_seckill_voucher;
DROP TABLE IF EXISTS tb_voucher;
DROP TABLE IF EXISTS tb_blog_comments;
DROP TABLE IF EXISTS tb_blog;
DROP TABLE IF EXISTS tb_follow;
DROP TABLE IF EXISTS tb_shop;
DROP TABLE IF EXISTS tb_shop_type;
DROP TABLE IF EXISTS tb_user_info;
DROP TABLE IF EXISTS tb_user;

CREATE TABLE tb_user (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  phone VARCHAR(20) NOT NULL UNIQUE,
  password VARCHAR(128),
  nick_name VARCHAR(64) NOT NULL,
  icon VARCHAR(255) DEFAULT '',
  create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
  update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE tb_user_info (
  user_id BIGINT PRIMARY KEY,
  city VARCHAR(64),
  introduce VARCHAR(128),
  fans INT DEFAULT 0,
  followee INT DEFAULT 0,
  gender TINYINT(1),
  birthday DATE,
  credits INT DEFAULT 0,
  level TINYINT(1) DEFAULT 0,
  create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
  update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE tb_shop_type (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  name VARCHAR(64) NOT NULL,
  icon VARCHAR(255),
  sort INT DEFAULT 0,
  create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
  update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE tb_shop (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  name VARCHAR(128) NOT NULL,
  type_id BIGINT NOT NULL,
  images VARCHAR(1024),
  area VARCHAR(64),
  address VARCHAR(255),
  x DOUBLE,
  y DOUBLE,
  avg_price BIGINT DEFAULT 0,
  sold INT DEFAULT 0,
  comments INT DEFAULT 0,
  score INT DEFAULT 0,
  open_hours VARCHAR(64),
  create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
  update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_shop_type (type_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE tb_follow (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  user_id BIGINT NOT NULL,
  follow_user_id BIGINT NOT NULL,
  create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uk_follow (user_id, follow_user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE tb_blog (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  shop_id BIGINT,
  user_id BIGINT NOT NULL,
  title VARCHAR(128) NOT NULL,
  images VARCHAR(1024),
  content TEXT,
  liked INT DEFAULT 0,
  comments INT DEFAULT 0,
  create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
  update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_blog_user (user_id),
  INDEX idx_blog_liked (liked)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE tb_blog_comments (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  user_id BIGINT NOT NULL,
  blog_id BIGINT NOT NULL,
  parent_id BIGINT DEFAULT 0,
  answer_id BIGINT DEFAULT 0,
  content VARCHAR(512) NOT NULL,
  liked INT DEFAULT 0,
  status TINYINT(1) DEFAULT 0,
  create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
  update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE tb_voucher (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  shop_id BIGINT NOT NULL,
  title VARCHAR(128) NOT NULL,
  sub_title VARCHAR(255),
  rules VARCHAR(1024),
  pay_value BIGINT NOT NULL,
  actual_value BIGINT NOT NULL,
  type INT DEFAULT 0,
  status INT DEFAULT 1,
  create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
  update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_voucher_shop (shop_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE tb_seckill_voucher (
  voucher_id BIGINT PRIMARY KEY,
  stock INT NOT NULL,
  create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
  begin_time DATETIME NOT NULL,
  end_time DATETIME NOT NULL,
  update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE tb_voucher_order (
  id BIGINT PRIMARY KEY,
  user_id BIGINT NOT NULL,
  voucher_id BIGINT NOT NULL,
  pay_type INT DEFAULT 1,
  status INT DEFAULT 1,
  create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
  pay_time DATETIME NULL,
  use_time DATETIME NULL,
  refund_time DATETIME NULL,
  update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_user_voucher (user_id, voucher_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
